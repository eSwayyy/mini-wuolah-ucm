/*
    REPORTES (3 DASHBOARDS)
    CADA PROCEDIMIENTO ENTREGA SUS RESULTADOS EN CURSORES DE SALIDA
*/

-- ======================================================================
-- REPORTE 1: APUNTES MAS DESCARGADOS Y DESCARGAS POR CARRERA
-- FILTROS OPCIONALES: ASIGNATURA Y ANIO (SI VIENEN NULOS NO FILTRAN)
-- LA CARRERA ES LA DEL USUARIO QUE DESCARGA
-- ======================================================================

CREATE OR REPLACE PROCEDURE WU_REP_TOP_DESCARGAS_P(
    ID_ASIGNATURA_P NUMBER,
    ANIO_P NUMBER,
    CURSOR_APUNTES_P OUT SYS_REFCURSOR,
    CURSOR_CARRERAS_P OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_APUNTES_P FOR
        SELECT A.ID_APUNTE, A.TITULO, S.NOMBRE AS ASIGNATURA, COUNT(DE.ID_DESCARGA) AS TOTAL_DESCARGAS
        FROM WU_DESCARGA DE JOIN WU_APUNTE A ON(DE.ID_APUNTE = A.ID_APUNTE)
             JOIN WU_ASIGNATURA S ON(A.ID_ASIGNATURA = S.ID_ASIGNATURA)
        WHERE (ID_ASIGNATURA_P IS NULL OR S.ID_ASIGNATURA = ID_ASIGNATURA_P)
          AND (ANIO_P IS NULL OR TO_NUMBER(TO_CHAR(DE.FECHA_DESCARGA, 'YYYY'), '9999') = ANIO_P)
        GROUP BY A.ID_APUNTE, A.TITULO, S.NOMBRE
        ORDER BY 4 DESC, 2;

    OPEN CURSOR_CARRERAS_P FOR
        SELECT C.NOMBRE AS CARRERA, COUNT(DE.ID_DESCARGA) AS TOTAL_DESCARGAS
        FROM WU_DESCARGA DE JOIN WU_USUARIO U ON(DE.ID_USUARIO = U.ID_USUARIO)
             JOIN WU_CARRERA C ON(U.ID_CARRERA = C.ID_CARRERA)
        WHERE (ANIO_P IS NULL OR TO_NUMBER(TO_CHAR(DE.FECHA_DESCARGA, 'YYYY'), '9999') = ANIO_P)
        GROUP BY C.NOMBRE
        ORDER BY 2 DESC, 1;
END WU_REP_TOP_DESCARGAS_P;
/

-- ======================================================================
-- REPORTE 2: ACTIVIDAD MENSUAL DE UN ANIO (DESCARGAS Y APUNTES SUBIDOS)
-- ======================================================================

CREATE OR REPLACE PROCEDURE WU_REP_ACTIVIDAD_MENSUAL_P(
    ANIO_P NUMBER,
    CURSOR_DESCARGAS_P OUT SYS_REFCURSOR,
    CURSOR_APUNTES_P OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_DESCARGAS_P FOR
        SELECT TO_CHAR(FECHA_DESCARGA, 'YYYY-MM') AS MES, COUNT(*) AS TOTAL
        FROM WU_DESCARGA
        WHERE TO_NUMBER(TO_CHAR(FECHA_DESCARGA, 'YYYY'), '9999') = ANIO_P
        GROUP BY TO_CHAR(FECHA_DESCARGA, 'YYYY-MM')
        ORDER BY 1;

    OPEN CURSOR_APUNTES_P FOR
        SELECT TO_CHAR(FECHA_SUBIDA, 'YYYY-MM') AS MES, COUNT(*) AS TOTAL
        FROM WU_APUNTE
        WHERE TO_NUMBER(TO_CHAR(FECHA_SUBIDA, 'YYYY'), '9999') = ANIO_P
        GROUP BY TO_CHAR(FECHA_SUBIDA, 'YYYY-MM')
        ORDER BY 1;
END WU_REP_ACTIVIDAD_MENSUAL_P;
/

-- ======================================================================
-- REPORTE 3: COBERTURA DE MATERIAL POR ASIGNATURA DE CADA CARRERA
-- CURSOR 1: ASIGNATURAS CON APUNTES ACTIVOS
-- CURSOR 2: ASIGNATURAS SIN NINGUN APUNTE ACTIVO (NOT IN)
-- ======================================================================

CREATE OR REPLACE PROCEDURE WU_REP_COBERTURA_P(
    ID_CARRERA_P NUMBER,
    CURSOR_CON_MATERIAL_P OUT SYS_REFCURSOR,
    CURSOR_SIN_MATERIAL_P OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_CON_MATERIAL_P FOR
        SELECT S.CODIGO, S.NOMBRE AS ASIGNATURA, C.NOMBRE AS CARRERA,
               COUNT(A.ID_APUNTE) AS TOTAL_APUNTES,
               SUM(WU_TOTAL_DESCARGAS_F(A.ID_APUNTE)) AS TOTAL_DESCARGAS
        FROM WU_ASIGNATURA S JOIN WU_CARRERA_ASIGNATURA CA ON(S.ID_ASIGNATURA = CA.ID_ASIGNATURA)
             JOIN WU_CARRERA C ON(CA.ID_CARRERA = C.ID_CARRERA)
             JOIN WU_APUNTE A ON(A.ID_ASIGNATURA = S.ID_ASIGNATURA)
        WHERE A.ESTADO = 'ACTIVO'
          AND (ID_CARRERA_P IS NULL OR C.ID_CARRERA = ID_CARRERA_P)
        GROUP BY S.CODIGO, S.NOMBRE, C.NOMBRE
        ORDER BY 4 DESC, 2;

    OPEN CURSOR_SIN_MATERIAL_P FOR
        SELECT S.CODIGO, S.NOMBRE AS ASIGNATURA, C.NOMBRE AS CARRERA
        FROM WU_ASIGNATURA S JOIN WU_CARRERA_ASIGNATURA CA ON(S.ID_ASIGNATURA = CA.ID_ASIGNATURA)
             JOIN WU_CARRERA C ON(CA.ID_CARRERA = C.ID_CARRERA)
        WHERE S.ID_ASIGNATURA NOT IN (SELECT ID_ASIGNATURA FROM WU_APUNTE WHERE ESTADO = 'ACTIVO')
          AND (ID_CARRERA_P IS NULL OR C.ID_CARRERA = ID_CARRERA_P)
        ORDER BY C.NOMBRE, S.NOMBRE;
END WU_REP_COBERTURA_P;
/
