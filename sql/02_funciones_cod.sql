/*
    FUNCIONES QUE ENTREGAN EL SIGUIENTE CODIGO DE CADA SECUENCIA
    (SE USAN EN LOS INSERT DE LOS PROCEDIMIENTOS)
*/

CREATE OR REPLACE FUNCTION WU_SIGUIENTE_ID_FACULTAD_F
RETURN NUMBER
IS
    CODIGO_F NUMBER;
BEGIN
    SELECT WU_ID_FACULTAD.NEXTVAL
        INTO CODIGO_F
        FROM DUAL;
    RETURN CODIGO_F;
END WU_SIGUIENTE_ID_FACULTAD_F;
/

