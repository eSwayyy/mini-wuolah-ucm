-- DESCARGAS, VALORACIONES Y FAVORITOS GENERADOS DE FORMA REPETIBLE A PARTIR
-- DE LOS APUNTES ACTIVOS (NADIE INTERACTUA CON SU PROPIO APUNTE).
-- LAS DESCARGAS DISPARAN WU_DESCARGA_AI_T Y LAS VALORACIONES WU_VALORACION_BI_T.
DECLARE
    CURSOR C_APUNTES IS
        SELECT ID_APUNTE, ID_USUARIO, FECHA_SUBIDA
        FROM WU_APUNTE
        WHERE ESTADO = 'ACTIVO'
        ORDER BY ID_APUNTE;

    CURSOR C_PARES IS
        SELECT ID_APUNTE, ID_USUARIO, MIN(FECHA_DESCARGA) AS PRIMERA
        FROM WU_DESCARGA
        GROUP BY ID_APUNTE, ID_USUARIO
        ORDER BY ID_APUNTE, ID_USUARIO;

    HOY_V DATE := DATE '2026-11-16';
    FECHA_V DATE;
BEGIN
    FOR AP IN C_APUNTES LOOP
        FOR U IN 2..4 LOOP
            IF U <> AP.ID_USUARIO
               AND MOD(AP.ID_APUNTE * 7 + U * 3, 10) < 7 + MOD(AP.ID_APUNTE, 3) THEN
                FECHA_V := AP.FECHA_SUBIDA + 1 + MOD(AP.ID_APUNTE * 5 + U * 3, 45);
                IF FECHA_V > HOY_V THEN
                    FECHA_V := HOY_V;
                END IF;

                INSERT INTO WU_DESCARGA(ID_DESCARGA, ID_USUARIO, ID_APUNTE, FECHA_DESCARGA)
                VALUES (WU_ID_DESCARGA.NEXTVAL, U, AP.ID_APUNTE, FECHA_V);
            END IF;
        END LOOP;
    END LOOP;

    FOR PAR IN C_PARES LOOP
        -- VALORACIONES: APROXIMADAMENTE 4 DE CADA 5 DESCARGAS
        IF MOD(PAR.ID_APUNTE * PAR.ID_USUARIO, 5) <> 0 THEN
            FECHA_V := PAR.PRIMERA + 1;
            IF FECHA_V > HOY_V THEN
                FECHA_V := HOY_V;
            END IF;

            INSERT INTO WU_VALORACION(ID_VALORACION, ID_USUARIO, ID_APUNTE, PUNTUACION, FECHA_VALORACION)
            VALUES (WU_ID_VALORACION.NEXTVAL, PAR.ID_USUARIO, PAR.ID_APUNTE,
                    2 + MOD(PAR.ID_APUNTE + 2 * PAR.ID_USUARIO, 4), FECHA_V);
        END IF;

        -- FAVORITOS: ALGUNOS APUNTES DESCARGADOS
        IF MOD(PAR.ID_APUNTE + PAR.ID_USUARIO, 5) = 0 THEN
            FECHA_V := PAR.PRIMERA + 2;
            IF FECHA_V > HOY_V THEN
                FECHA_V := HOY_V;
            END IF;

            INSERT INTO WU_FAVORITO(ID_USUARIO, ID_APUNTE, FECHA_FAVORITO)
            VALUES (PAR.ID_USUARIO, PAR.ID_APUNTE, FECHA_V);
        END IF;
    END LOOP;
END;
