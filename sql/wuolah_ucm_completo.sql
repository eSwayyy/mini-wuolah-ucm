-- REPUTACION DE UN USUARIO: POR CADA APUNTE APROBADO SUMA 10 PUNTOS,
-- MAS UN PUNTO POR DESCARGA, MAS EL PROMEDIO DE VALORACION POR 2 (CURSOR EXPLICITO)
CREATE OR REPLACE FUNCTION WU_REPUTACION_F(
    ID_USUARIO_P NUMBER
)
RETURN NUMBER
IS
    CURSOR C_APUNTES IS
        SELECT ID_APUNTE
        FROM WU_APUNTE
        WHERE ID_USUARIO = ID_USUARIO_P AND ESTADO = 'ACTIVO';

    ID_APUNTE_C WU_APUNTE.ID_APUNTE%TYPE;
    PUNTOS_V NUMBER := 0;
BEGIN
    OPEN C_APUNTES;
    LOOP
        FETCH C_APUNTES INTO ID_APUNTE_C;
        EXIT WHEN C_APUNTES%NOTFOUND;

        PUNTOS_V := PUNTOS_V + 10
                    + WU_TOTAL_DESCARGAS_F(ID_APUNTE_C)
                    + ROUND(WU_PROMEDIO_VALORACION_F(ID_APUNTE_C) * 2);
    END LOOP;
    CLOSE C_APUNTES;

    RETURN PUNTOS_V;
EXCEPTION
    WHEN OTHERS THEN
        IF C_APUNTES%ISOPEN THEN
            CLOSE C_APUNTES;
        END IF;
        RETURN -99;
END WU_REPUTACION_F;
/

