    )
    VALUES(
        ID_APUNTE_P,
        ID_USUARIO_P,
        ID_ASIGNATURA_P,
        ID_TIPO_P,
        ID_PROFESOR_P,
        TITULO_P,
        DESCRIPCION_P,
        RUTA_ARCHIVO_P,
        SYSDATE,
        'PENDIENTE'
    );

    -- ETIQUETAS: SE IGNORAN LAS NULAS Y LAS REPETIDAS
    FOR I IN 1..3 LOOP
        IF I = 1 THEN
            ETIQUETA_V := ID_ETIQUETA1_P;
        ELSIF I = 2 THEN
            ETIQUETA_V := ID_ETIQUETA2_P;
        ELSE
