-- ======================================================================
-- TABLAS (MODELO EN 3FN)
-- ======================================================================

CREATE TABLE WU_FACULTAD(
    ID_FACULTAD NUMBER,
    NOMBRE VARCHAR2(120) NOT NULL,
    CONSTRAINT PK_WU_FACULTAD PRIMARY KEY(ID_FACULTAD),
    CONSTRAINT UK_WU_FACULTAD UNIQUE(NOMBRE)
);

CREATE TABLE WU_CARRERA(
    ID_CARRERA NUMBER,
    CODIGO VARCHAR2(20) NOT NULL,
    NOMBRE VARCHAR2(150) NOT NULL,
    ID_FACULTAD NUMBER NOT NULL,
    CONSTRAINT PK_WU_CARRERA PRIMARY KEY(ID_CARRERA),
    CONSTRAINT UK_WU_CARRERA_CODIGO UNIQUE(CODIGO),
    CONSTRAINT UK_WU_CARRERA_NOMBRE UNIQUE(NOMBRE),
    CONSTRAINT FK_WU_CARRERA_FACULTAD FOREIGN KEY(ID_FACULTAD) REFERENCES WU_FACULTAD(ID_FACULTAD)
);

CREATE TABLE WU_PROFESOR(
    ID_PROFESOR NUMBER,
    NOMBRE VARCHAR2(80) NOT NULL,
    APELLIDO VARCHAR2(80) NOT NULL,
    ID_FACULTAD NUMBER NOT NULL,
    CONSTRAINT PK_WU_PROFESOR PRIMARY KEY(ID_PROFESOR),
    CONSTRAINT FK_WU_PROFESOR_FACULTAD FOREIGN KEY(ID_FACULTAD) REFERENCES WU_FACULTAD(ID_FACULTAD)
);

CREATE TABLE WU_ASIGNATURA(
    ID_ASIGNATURA NUMBER,
    CODIGO VARCHAR2(20) NOT NULL,
    NOMBRE VARCHAR2(150) NOT NULL,
    CONSTRAINT PK_WU_ASIGNATURA PRIMARY KEY(ID_ASIGNATURA),
    CONSTRAINT UK_WU_ASIGNATURA_CODIGO UNIQUE(CODIGO)
);

-- UNA ASIGNATURA PUEDE PERTENECER A VARIAS CARRERAS (RELACION N:M)
CREATE TABLE WU_CARRERA_ASIGNATURA(
    ID_CARRERA NUMBER,
    ID_ASIGNATURA NUMBER,
    SEMESTRE NUMBER(2) NOT NULL,
    CONSTRAINT PK_WU_CARRERA_ASIGNATURA PRIMARY KEY(ID_CARRERA, ID_ASIGNATURA),
    CONSTRAINT CK_WU_CA_SEMESTRE CHECK(SEMESTRE BETWEEN 1 AND 12),
    CONSTRAINT FK_WU_CA_CARRERA FOREIGN KEY(ID_CARRERA) REFERENCES WU_CARRERA(ID_CARRERA),
    CONSTRAINT FK_WU_CA_ASIGNATURA FOREIGN KEY(ID_ASIGNATURA) REFERENCES WU_ASIGNATURA(ID_ASIGNATURA)
);

CREATE TABLE WU_USUARIO(
    ID_USUARIO NUMBER,
    ID_CARRERA NUMBER,
    NOMBRE VARCHAR2(100) NOT NULL,
    CORREO VARCHAR2(150) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROL VARCHAR2(20) NOT NULL,
    ESTADO VARCHAR2(10) NOT NULL,
    FECHA_REGISTRO DATE NOT NULL,
    CONSTRAINT PK_WU_USUARIO PRIMARY KEY(ID_USUARIO),
    CONSTRAINT UK_WU_USUARIO_CORREO UNIQUE(CORREO),
    CONSTRAINT CK_WU_USUARIO_ROL CHECK(ROL IN ('ESTUDIANTE','ADMIN')),
    CONSTRAINT CK_WU_USUARIO_ESTADO CHECK(ESTADO IN ('ACTIVO','BLOQUEADO')),
    CONSTRAINT FK_WU_USUARIO_CARRERA FOREIGN KEY(ID_CARRERA) REFERENCES WU_CARRERA(ID_CARRERA)
);

-- TIPO DE APUNTE: RESUMEN, GUIA, PRUEBA, ETC.
CREATE TABLE WU_TIPO_APUNTE(
    ID_TIPO NUMBER,
    NOMBRE VARCHAR2(60) NOT NULL,
    CONSTRAINT PK_WU_TIPO_APUNTE PRIMARY KEY(ID_TIPO),
    CONSTRAINT UK_WU_TIPO_APUNTE UNIQUE(NOMBRE)
);

CREATE TABLE WU_ETIQUETA(
    ID_ETIQUETA NUMBER,
    NOMBRE VARCHAR2(40) NOT NULL,
    CONSTRAINT PK_WU_ETIQUETA PRIMARY KEY(ID_ETIQUETA),
    CONSTRAINT UK_WU_ETIQUETA UNIQUE(NOMBRE)
);

-- ESTADO: PENDIENTE (RECIEN SUBIDO) -> ACTIVO (APROBADO) O RECHAZADO; OCULTO LO USA EL ADMIN
CREATE TABLE WU_APUNTE(
    ID_APUNTE NUMBER,
    ID_USUARIO NUMBER NOT NULL,
    ID_ASIGNATURA NUMBER NOT NULL,
    ID_TIPO NUMBER NOT NULL,
    ID_PROFESOR NUMBER,
    TITULO VARCHAR2(200) NOT NULL,
    DESCRIPCION VARCHAR2(1000),
    RUTA_ARCHIVO VARCHAR2(500) NOT NULL,
    FECHA_SUBIDA DATE NOT NULL,
    ESTADO VARCHAR2(10) NOT NULL,
    CONSTRAINT PK_WU_APUNTE PRIMARY KEY(ID_APUNTE),
    CONSTRAINT CK_WU_APUNTE_ESTADO CHECK(ESTADO IN ('PENDIENTE','ACTIVO','RECHAZADO','OCULTO')),
    CONSTRAINT FK_WU_APUNTE_USUARIO FOREIGN KEY(ID_USUARIO) REFERENCES WU_USUARIO(ID_USUARIO),
    CONSTRAINT FK_WU_APUNTE_ASIGNATURA FOREIGN KEY(ID_ASIGNATURA) REFERENCES WU_ASIGNATURA(ID_ASIGNATURA),
    CONSTRAINT FK_WU_APUNTE_TIPO FOREIGN KEY(ID_TIPO) REFERENCES WU_TIPO_APUNTE(ID_TIPO),
    CONSTRAINT FK_WU_APUNTE_PROFESOR FOREIGN KEY(ID_PROFESOR) REFERENCES WU_PROFESOR(ID_PROFESOR)
);

-- RELACION N:M ENTRE APUNTE Y ETIQUETA
CREATE TABLE WU_APUNTE_ETIQUETA(
    ID_APUNTE NUMBER,
    ID_ETIQUETA NUMBER,
    CONSTRAINT PK_WU_APUNTE_ETIQUETA PRIMARY KEY(ID_APUNTE, ID_ETIQUETA),
    CONSTRAINT FK_WU_APETIQ_APUNTE FOREIGN KEY(ID_APUNTE) REFERENCES WU_APUNTE(ID_APUNTE),
    CONSTRAINT FK_WU_APETIQ_ETIQUETA FOREIGN KEY(ID_ETIQUETA) REFERENCES WU_ETIQUETA(ID_ETIQUETA)
);

CREATE TABLE WU_DESCARGA(
    ID_DESCARGA NUMBER,
    ID_USUARIO NUMBER NOT NULL,
    ID_APUNTE NUMBER NOT NULL,
    FECHA_DESCARGA DATE NOT NULL,
    CONSTRAINT PK_WU_DESCARGA PRIMARY KEY(ID_DESCARGA),
    CONSTRAINT FK_WU_DESCARGA_USUARIO FOREIGN KEY(ID_USUARIO) REFERENCES WU_USUARIO(ID_USUARIO),
    CONSTRAINT FK_WU_DESCARGA_APUNTE FOREIGN KEY(ID_APUNTE) REFERENCES WU_APUNTE(ID_APUNTE)
);

CREATE TABLE WU_VALORACION(
    ID_VALORACION NUMBER,
    ID_USUARIO NUMBER NOT NULL,
    ID_APUNTE NUMBER NOT NULL,
    PUNTUACION NUMBER(1) NOT NULL,
    FECHA_VALORACION DATE NOT NULL,
    CONSTRAINT PK_WU_VALORACION PRIMARY KEY(ID_VALORACION),
    CONSTRAINT UK_WU_VALORACION UNIQUE(ID_USUARIO, ID_APUNTE),
    CONSTRAINT CK_WU_VALORACION_PUNTUACION CHECK(PUNTUACION BETWEEN 1 AND 5),
    CONSTRAINT FK_WU_VALORACION_USUARIO FOREIGN KEY(ID_USUARIO) REFERENCES WU_USUARIO(ID_USUARIO),
    CONSTRAINT FK_WU_VALORACION_APUNTE FOREIGN KEY(ID_APUNTE) REFERENCES WU_APUNTE(ID_APUNTE)
);

CREATE TABLE WU_FAVORITO(
    ID_USUARIO NUMBER,
    ID_APUNTE NUMBER,
    FECHA_FAVORITO DATE NOT NULL,
    CONSTRAINT PK_WU_FAVORITO PRIMARY KEY(ID_USUARIO, ID_APUNTE),
    CONSTRAINT FK_WU_FAVORITO_USUARIO FOREIGN KEY(ID_USUARIO) REFERENCES WU_USUARIO(ID_USUARIO),
    CONSTRAINT FK_WU_FAVORITO_APUNTE FOREIGN KEY(ID_APUNTE) REFERENCES WU_APUNTE(ID_APUNTE)
);

CREATE TABLE WU_COMENTARIO(
    ID_COMENTARIO NUMBER,
    ID_USUARIO NUMBER NOT NULL,
    ID_APUNTE NUMBER NOT NULL,
    CONTENIDO VARCHAR2(1000) NOT NULL,
    FECHA_COMENTARIO DATE NOT NULL,
    VISIBLE NUMBER(1) NOT NULL,
    CONSTRAINT PK_WU_COMENTARIO PRIMARY KEY(ID_COMENTARIO),
    CONSTRAINT CK_WU_COMENTARIO_VISIBLE CHECK(VISIBLE IN (0,1)),
    CONSTRAINT FK_WU_COMENTARIO_USUARIO FOREIGN KEY(ID_USUARIO) REFERENCES WU_USUARIO(ID_USUARIO),
    CONSTRAINT FK_WU_COMENTARIO_APUNTE FOREIGN KEY(ID_APUNTE) REFERENCES WU_APUNTE(ID_APUNTE)
);

CREATE TABLE WU_MODERACION(
    ID_MODERACION NUMBER,
    ID_APUNTE NUMBER NOT NULL,
    ID_ADMIN NUMBER NOT NULL,
    DECISION VARCHAR2(10) NOT NULL,
    MOTIVO VARCHAR2(500),
    FECHA_MODERACION DATE NOT NULL,
    CONSTRAINT PK_WU_MODERACION PRIMARY KEY(ID_MODERACION),
    CONSTRAINT CK_WU_MODERACION_DECISION CHECK(DECISION IN ('ACTIVO','RECHAZADO')),
    CONSTRAINT FK_WU_MODERACION_APUNTE FOREIGN KEY(ID_APUNTE) REFERENCES WU_APUNTE(ID_APUNTE),
    CONSTRAINT FK_WU_MODERACION_ADMIN FOREIGN KEY(ID_ADMIN) REFERENCES WU_USUARIO(ID_USUARIO)
);

-- TABLA DE LOG QUE ALIMENTAN LOS TRIGGERS (SOLO SE INSERTA, NUNCA SE MODIFICA)
CREATE TABLE WU_AUDITORIA(
    ID_AUDITORIA NUMBER,
    TABLA VARCHAR2(30) NOT NULL,
    OPERACION VARCHAR2(20) NOT NULL,
    ID_REGISTRO NUMBER,
    USUARIO_BD VARCHAR2(60) NOT NULL,
    DETALLE VARCHAR2(500),
    FECHA_AUDITORIA DATE NOT NULL,
    CONSTRAINT PK_WU_AUDITORIA PRIMARY KEY(ID_AUDITORIA)
);

