CREATE OR REPLACE PROCEDURE WU_COMENTARIOS_APUNTE_P(
    ID_APUNTE_P NUMBER,
    CURSOR_P OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_P FOR
        SELECT C.ID_COMENTARIO, C.ID_USUARIO, U.NOMBRE AS AUTOR, C.CONTENIDO, C.FECHA_COMENTARIO
        FROM WU_COMENTARIO C JOIN WU_USUARIO U ON(C.ID_USUARIO = U.ID_USUARIO)
        WHERE C.ID_APUNTE = ID_APUNTE_P AND C.VISIBLE = 1
        ORDER BY C.FECHA_COMENTARIO DESC, C.ID_COMENTARIO DESC;
END WU_COMENTARIOS_APUNTE_P;
/

-- ASIGNATURAS DE UNA CARRERA (SI LA CARRERA ES NULA ENTREGA TODAS, SIN REPETIR)
CREATE OR REPLACE PROCEDURE WU_ASIGNATURAS_CARRERA_P(
    ID_CARRERA_P NUMBER,
    CURSOR_P OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_P FOR
        SELECT S.ID_ASIGNATURA, S.CODIGO, S.NOMBRE
        FROM WU_ASIGNATURA S
        WHERE ID_CARRERA_P IS NULL
           OR S.ID_ASIGNATURA IN (SELECT ID_ASIGNATURA FROM WU_CARRERA_ASIGNATURA WHERE ID_CARRERA = ID_CARRERA_P)
        ORDER BY S.NOMBRE;
END WU_ASIGNATURAS_CARRERA_P;
/

-- DATOS PUBLICOS DE UN USUARIO (PERFIL)
CREATE OR REPLACE PROCEDURE WU_USUARIO_OBTENER_P(
    ID_USUARIO_P NUMBER,
    CURSOR_P OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_P FOR
        SELECT U.ID_USUARIO, U.NOMBRE, U.CORREO, U.ROL, U.ESTADO, U.FECHA_REGISTRO, U.ID_CARRERA,
               WU_NOMBRE_CARRERA_F(U.ID_CARRERA) AS CARRERA, WU_REPUTACION_F(U.ID_USUARIO) AS REPUTACION
        FROM WU_USUARIO U
        WHERE U.ID_USUARIO = ID_USUARIO_P;
END WU_USUARIO_OBTENER_P;
