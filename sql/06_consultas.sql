CREATE OR REPLACE PROCEDURE WU_APUNTE_LISTAR_P(
    ESTADO_P VARCHAR2,
    CURSOR_P OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_P FOR
        SELECT A.ID_APUNTE, A.TITULO, A.DESCRIPCION, A.RUTA_ARCHIVO, A.ESTADO, A.FECHA_SUBIDA,
               A.ID_USUARIO, U.NOMBRE AS AUTOR, WU_NOMBRE_CARRERA_F(U.ID_CARRERA) AS CARRERA_AUTOR,
               A.ID_ASIGNATURA, S.CODIGO AS CODIGO_ASIGNATURA, S.NOMBRE AS ASIGNATURA,
               A.ID_TIPO, T.NOMBRE AS TIPO,
               A.ID_PROFESOR, WU_NOMBRE_PROFESOR_F(A.ID_PROFESOR) AS PROFESOR,
               WU_TOTAL_DESCARGAS_F(A.ID_APUNTE) AS DESCARGAS,
               WU_PROMEDIO_VALORACION_F(A.ID_APUNTE) AS PROMEDIO,
               WU_TOTAL_VALORACIONES_F(A.ID_APUNTE) AS TOTAL_VALORACIONES,
               WU_TOTAL_FAVORITOS_F(A.ID_APUNTE) AS FAVORITOS,
               WU_TOTAL_COMENTARIOS_F(A.ID_APUNTE) AS COMENTARIOS
        FROM WU_APUNTE A JOIN WU_USUARIO U ON(A.ID_USUARIO = U.ID_USUARIO)
             JOIN WU_ASIGNATURA S ON(A.ID_ASIGNATURA = S.ID_ASIGNATURA)
             JOIN WU_TIPO_APUNTE T ON(A.ID_TIPO = T.ID_TIPO)
        WHERE (ESTADO_P IS NULL OR A.ESTADO = ESTADO_P)
        ORDER BY A.FECHA_SUBIDA DESC, A.ID_APUNTE DESC;
END WU_APUNTE_LISTAR_P;
/

