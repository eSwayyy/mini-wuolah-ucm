/*
    ELIMINA LOS OBJETOS DEL PROYECTO (PREFIJO WU_) PARA PODER CARGARLO DESDE CERO
    SI EL ESQUEMA ESTA VACIO NO MUESTRA ERRORES. LOS TRIGGERS SE ELIMINAN JUNTO CON SUS TABLAS
*/

BEGIN
    -- PRIMERO LAS TABLAS, CON SUS RESTRICCIONES
    FOR TABLA_C IN (SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME LIKE 'WU\_%' ESCAPE '\') LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || TABLA_C.TABLE_NAME || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;

    -- LUEGO PROCEDIMIENTOS, FUNCIONES Y SECUENCIAS
    FOR OBJETO_C IN (SELECT OBJECT_NAME, OBJECT_TYPE FROM USER_OBJECTS
                     WHERE OBJECT_NAME LIKE 'WU\_%' ESCAPE '\'
                       AND OBJECT_TYPE IN ('PROCEDURE', 'FUNCTION', 'SEQUENCE')) LOOP
        EXECUTE IMMEDIATE 'DROP ' || OBJETO_C.OBJECT_TYPE || ' ' || OBJETO_C.OBJECT_NAME;
    END LOOP;
END;
/
