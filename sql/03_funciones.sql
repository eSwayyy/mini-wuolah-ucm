-- RETORNA 1 SI EL USUARIO ES ADMIN, 0 SI NO LO ES Y -1 SI NO EXISTE
CREATE OR REPLACE FUNCTION WU_ES_ADMIN_F(
    ID_USUARIO_P NUMBER
)
RETURN NUMBER
IS
    ROL_F WU_USUARIO.ROL%TYPE;
BEGIN
    SELECT ROL
        INTO ROL_F
        FROM WU_USUARIO
        WHERE ID_USUARIO = ID_USUARIO_P;

    IF ROL_F = 'ADMIN' THEN
        RETURN 1;
    ELSE
        RETURN 0;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN -1;
    WHEN OTHERS THEN
        RETURN -99;
END WU_ES_ADMIN_F;
/

-- RETORNA 1 SI EL USUARIO ESTA ACTIVO, 0 SI ESTA BLOQUEADO Y -1 SI NO EXISTE
CREATE OR REPLACE FUNCTION WU_USUARIO_ACTIVO_F(
    ID_USUARIO_P NUMBER
)
RETURN NUMBER
IS
    ESTADO_F WU_USUARIO.ESTADO%TYPE;
BEGIN
    SELECT ESTADO
        INTO ESTADO_F
        FROM WU_USUARIO
        WHERE ID_USUARIO = ID_USUARIO_P;

    IF ESTADO_F = 'ACTIVO' THEN
        RETURN 1;
    ELSE
        RETURN 0;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN -1;
    WHEN OTHERS THEN
        RETURN -99;
END WU_USUARIO_ACTIVO_F;
/

-- RETORNA EL ESTADO DEL APUNTE O 'NO_EXISTE' SI EL CODIGO NO ESTA REGISTRADO
