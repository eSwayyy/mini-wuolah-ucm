-- ======================================================================
-- DESCARGAS, VALORACIONES
-- ======================================================================

CREATE OR REPLACE FUNCTION WU_TOTAL_DESCARGAS_F(
    ID_APUNTE_P NUMBER
)
RETURN NUMBER
IS
    TOTAL_F NUMBER;
BEGIN
    SELECT COUNT(*)
        INTO TOTAL_F
        FROM WU_DESCARGA
        WHERE ID_APUNTE = ID_APUNTE_P;
    RETURN TOTAL_F;
EXCEPTION
    WHEN OTHERS THEN
        RETURN -99;
END WU_TOTAL_DESCARGAS_F;
/

