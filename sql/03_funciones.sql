-- RETORNA 1 SI EL CORREO YA ESTA REGISTRADO Y 0 SI NO
CREATE OR REPLACE FUNCTION WU_CORREO_EXISTE_F(
    CORREO_P VARCHAR2
)
RETURN NUMBER
IS
    TOTAL_F NUMBER;
BEGIN
    SELECT COUNT(*)
        INTO TOTAL_F
        FROM WU_USUARIO
        WHERE LOWER(CORREO) = LOWER(CORREO_P);

    IF TOTAL_F > 0 THEN
        RETURN 1;
    ELSE
        RETURN 0;
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        RETURN -99;
END WU_CORREO_EXISTE_F;
/

-- REPUTACION DE UN USUARIO: POR CADA APUNTE APROBADO SUMA 10 PUNTOS,
-- MAS UN PUNTO POR DESCARGA, MAS EL PROMEDIO DE VALORACION POR 2 (CURSOR EXPLICITO)
CREATE OR REPLACE FUNCTION WU_REPUTACION_F(
    ID_USUARIO_P NUMBER
)
RETURN NUMBER
IS
    CURSOR C_APUNTES IS
        SELECT ID_APUNTE
        FROM WU_APUNTE
        WHERE ID_USUARIO = ID_USUARIO_P AND ESTADO = 'ACTIVO';

    ID_APUNTE_C WU_APUNTE.ID_APUNTE%TYPE;
    PUNTOS_V NUMBER := 0;
BEGIN
    OPEN C_APUNTES;
    LOOP
        FETCH C_APUNTES INTO ID_APUNTE_C;
        EXIT WHEN C_APUNTES%NOTFOUND;

        PUNTOS_V := PUNTOS_V + 10
                    + WU_TOTAL_DESCARGAS_F(ID_APUNTE_C)
                    + ROUND(WU_PROMEDIO_VALORACION_F(ID_APUNTE_C) * 2);
    END LOOP;
    CLOSE C_APUNTES;

    RETURN PUNTOS_V;
EXCEPTION
    WHEN OTHERS THEN
        IF C_APUNTES%ISOPEN THEN
            CLOSE C_APUNTES;
        END IF;
        RETURN -99;
END WU_REPUTACION_F;
/

-- ======================================================================
-- AUDITORIA (LA INVOCAN LOS TRIGGERS, POR ESO NO HACE COMMIT)
-- ======================================================================

CREATE OR REPLACE PROCEDURE WU_REGISTRAR_AUDITORIA_P(
    TABLA_P VARCHAR2,
    OPERACION_P VARCHAR2,
    ID_REGISTRO_P NUMBER,
    DETALLE_P VARCHAR2
)
IS
BEGIN
    INSERT INTO WU_AUDITORIA(
        ID_AUDITORIA,
        TABLA,
        OPERACION,
        ID_REGISTRO,
        USUARIO_BD,
        DETALLE,
        FECHA_AUDITORIA
    )
    VALUES(
        WU_SIGUIENTE_ID_AUDITORIA_F(),
        TABLA_P,
        OPERACION_P,
        ID_REGISTRO_P,
        USER,
        SUBSTR(DETALLE_P, 1, 500),
        SYSDATE
    );
END WU_REGISTRAR_AUDITORIA_P;
/
