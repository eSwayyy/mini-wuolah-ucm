-- SI EL APUNTE NO TIENE VALORACIONES RETORNA 0
CREATE OR REPLACE FUNCTION WU_PROMEDIO_VALORACION_F(
    ID_APUNTE_P NUMBER
)
RETURN NUMBER
IS
    PROMEDIO_F NUMBER;
BEGIN
    SELECT AVG(PUNTUACION)
        INTO PROMEDIO_F
        FROM WU_VALORACION
        WHERE ID_APUNTE = ID_APUNTE_P;

    IF PROMEDIO_F IS NULL THEN
        RETURN 0;
    ELSE
        RETURN ROUND(PROMEDIO_F, 1);
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        RETURN -99;
END WU_PROMEDIO_VALORACION_F;
/

